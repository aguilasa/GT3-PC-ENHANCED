#!/usr/bin/env python3
"""Writes tools/platform_tests/eucjp_samples.txt, the samples eucjp_test
checks the EUC-JP codec (src/platform/os/eucjp.cpp) with, from the databases
of an installed data folder that the Windows build made (the launcher
converts the disc's paramunistr, carcolor.sdb and realtime.dat with code page
20932: platform/param_db.cpp).  Read only.

    python3 tools/platform_tests/gen_eucjp_samples.py <data folder> <c_20932.nls> > tools/platform_tests/eucjp_samples.txt

What the Windows build decided is the sample:
  T <hex> <text>  a string it stored as text: code page 20932 decodes <hex> to
                  <text> and encodes <text> back to <hex> (the bytes are
                  <text> encoded with the code page file's WideCharToMultiByte
                  table, which the round trip param_db requires makes the
                  disc's own);
  B <hex>         a string it kept as bytes (a BLOB): code page 20932 does not
                  decode them.
Only strings in the code page itself (none with the Latin-1 escape 0x81 of
param_db's own); the fewest strings that hold every character met."""
import glob
import importlib.util
import os
import sqlite3
import sys


def main():
    folder, nls = sys.argv[1], sys.argv[2]
    spec = importlib.util.spec_from_file_location(
        'gen', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen_cp20932_table.py'))
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    info, _, _, wc = gen.load(nls)

    texts, blobs = set(), set()
    for path in sorted(glob.glob(os.path.join(folder, '*', '*.sqlite3'))):
        db = sqlite3.connect('file:' + path + '?mode=ro', uri=True)
        for (table,) in db.execute("select name from sqlite_master where type='table'"):
            for col in [r[1] for r in db.execute('pragma table_info("%s")' % table)]:
                for (v,) in db.execute('select "%s" from "%s"' % (col, table)):
                    if isinstance(v, str) and any(ord(c) > 0x7F for c in v):
                        texts.add(v)
                    elif isinstance(v, bytes) and any(b > 0x7F for b in v) and 0x81 not in v and len(v) < 200:
                        blobs.add(v)
        db.close()

    def encode(s):
        out = bytearray()
        for c in s:
            u = ord(c)
            code = wc[u] if u < 0x10000 else info['def']
            if code == info['def'] and u != info['def']:
                return None
            out += bytes([code]) if code < 0x100 else bytes([code >> 8, code & 0xFF])
        return bytes(out)

    samples = []
    for t in sorted(texts):
        if any(0xA0 <= ord(c) <= 0xFF for c in t):
            continue                            # (the Latin-1 escape: param_db's, not the code page's)
        b = encode(t)
        if b is not None:
            samples.append((t, b))
    # the fewest strings holding every character (the shortest first among equals)
    need = set(c for t, _ in samples for c in t if ord(c) > 0x7F)
    chosen = []
    while need:
        best = max(samples, key=lambda s: (len(need & set(s[0])), -len(s[0])))
        chosen.append(best)
        need -= set(best[0])
    out = sys.stdout
    out.write('# eucjp_test samples: generated by gen_eucjp_samples.py from an installed\n'
              '# data folder made by the Windows build; do not edit.\n')
    for t, b in sorted(chosen, key=lambda s: s[1]):
        out.write('T %s %s\n' % (b.hex().upper(), t))
    for b in sorted(blobs):
        out.write('B %s\n' % b.hex().upper())


if __name__ == '__main__':
    main()
